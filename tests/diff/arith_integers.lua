-- integer arithmetic wraps around like C (two's complement, 64 bits)
local maxint, minint = math.maxinteger, math.mininteger
print(maxint, minint)
print(maxint + 1 == minint, minint - 1 == maxint)
print(maxint + 1, minint - 1, maxint * 2, minint * -1, -minint)
print(maxint * maxint, minint * minint, maxint * minint)
print(0x7fffffff * 0x7fffffff, 0x100000000 * 0x100000000, 123456789 * 987654321)
print(-9 // 2, 9 // -2, -9 // -2, 9 // 2, minint // -1, minint // 1)
print(-9 % 2, 9 % -2, -9 % -2, 9 % 2, minint % -1, 5 % maxint, -5 % maxint)
print(7 // 0.0, -7 // 0.0, 0/0 ~= 0/0, 7 % math.huge, -7 % math.huge)
print(5.5 // 2, -5.5 // 2, 5.5 % 2, -5.5 % 2, 5.5 % -2)
print(3 / 2, 4 / 2, 1 / 0, -1 / 0, 0 / 0 ~= 0 / 0)
print(2 ^ 10, 2 ^ 0.5, (-8) ^ (1/3) ~= (-8) ^ (1/3), 2 ^ 63, 2 ^ -1)
print(1 << 63, 1 << 64, 1 << -1, -1 >> 1, -1 >> 63, -1 >> 64, 3 << 62)
print(5 & 3, 5 | 3, 5 ~ 3, ~5, ~0, -1 & 0xFF, 0xF0 | 0x0F)
print(2.0 & 3, 1.0 << 2, ~1.0)
local x = 12
print(x + 1, x - 1, x * 3, x // 5, x % 5, x / 4, x ^ 2, x & 7, x | 1, x ~ 5, x << 2, x >> 2)
print(x + 1.5, x - 1.5, x * 1.5, x // 2.5, x % 2.5, x / 2.5)
local y = maxint
print(y + 1, y - (-1), y * 2, y + y)
local f = 1.5
print(f + 1, f - 1, f * 2, f // 1, f % 1, f / 2, -f, f ^ 2)
print(-x, -f, -(-x), - -f, -minint, -0.0, 0.0 == -0.0)
print(pcall(function () return 1 // 0 end))
print(pcall(function () return 1 % 0 end))
print(pcall(function () local z = 0; return x // z end))
print(pcall(function () local z = 0; return x % z end))
print(math.type(1), math.type(1.0), math.type(2^31), math.type(1//1), math.type(1.0//1))
print(0x10, 0xff, 0x7fffffffffffffff, 0xffffffffffffffff, 1e2, .5, 5e-1, 0x.8p1)
