-- pattern scans: a plain literal or one single character class (with no
-- suffix or with '+') answered by strpos/strcspn/strspn (MatchState's
-- simple shapes) and every case that takes the PCRE translation or the
-- port of lstrlib.c

local function show(...) print(select("#", ...), ...) end
local function try(f, ...) print(pcall(f, ...)) end

print("-- a plain literal")
local s = "hello world 123 aXbXc"
show(s:find("hello"))
show(s:find("o w"))
show(s:find("world", 8))
show(s:find("X", 15))
show(s:find("X", 16))
show(s:find("nope"))
show(s:match("hello"))
show(s:match("aXbXc"))
show(s:match("hello world 123 aXbXc"))
show(s:match(""))
show(("\0ab\0"):find("ab"))
show(("\0ab\0"):match("b\0"))
show(("a\0b"):gsub("\0", "-"))
show(s:gsub("X", "Y"))
show(s:gsub("item", "Z"))
show(s:gsub("hello", "%0!"))
show(s:gsub("l", { l = "L" }, 2))
show(s:gsub("l", function (c) return c:upper() end, 1))
show(s:gsub("l", 5))
show(s:gsub("l", "L", 0))
for w in ("aXbXc"):gmatch("X") do io.write("[", w, "]") end print()
for w in ("one two"):gmatch(" ") do io.write("[", w, "]") end print()

print("-- one character class")
show(s:find("[^ \t]"))
show(s:find("[^ \t]", 8))
show(s:find("[%d]"))
show(s:find("%d"))
show(s:match("%a"))
show(s:match("[a-f]"))
show(s:match("[^a-f]"))
show(s:match("[.]"))
show(s:match("[%.]"))
show(s:match("."))
show(s:find("^[^ ]+"))
show(s:match("^h"))
show(s:gsub("^hello", "HI"))
show(s:gsub("[,.]", "!"))
show(s:gsub("%u", "X"))
show(s:gsub(".", "-", 3))
show(("0\255z"):find("[%z\255]"))
show(("0\255z"):gsub("[%z\255]", "."))
show(("0\0z"):find("%z"))
show(("0\0z"):gsub("%z", "-"))
show(("tab\ttab"):match("%s"))
show(("~x~"):gsub("[~]", ""))
show(("x=y"):find("[=]"))
show(("x=y"):match("x%=y"))
show(("%d"):match("%%d"))
show(("A"):match("[^a-z]"))
show(("z9"):match("[a-f0-9]+"))

print("-- one character class run")
show(s:find("%a+"))
show(s:match("%a+"))
show(s:match("%d+"))
show(("aaa"):gsub("a+", "X"))
show(("aaa"):gsub("a+", "X", 1))
show(("a1b22c333"):gsub("%d+", "#"))
show(("  x  "):gsub("^%s+", ""):gsub("%s+$", ""))
show(("MULTI Case"):match("%u+"))
show(("q42"):match("[a-z]+"))
for w in ("aa bb ccc"):gmatch("%a+") do io.write(w, "|") end print()
for w in ("n1 n22"):gmatch("%d+") do io.write(w, "|") end print()
show(("x"):match("y+"))
show(("x"):find("y+"))
show(("\0\0x"):match("%z+"))
show(("..."):gsub("%.+", "-"))
show(("..."):match("%.+"))
show(("a-b"):match("[a%-b]+"))
show(("[]]x"):match("[]]+"))

print("-- both paths mixed")
show(s:gsub("[^ ]+", function (w) return #w end))
show(s:find("[%a]+"))
show(("k=v"):match("^([^=]+)="))
show(("a.b"):match("a.b"))
show(("a.b"):gsub("%.", "_"))
show(("aaa"):gsub("a-", "X"))
show(("abc"):match("b*"))
show(("ab"):gsub("()", "-"))
show(("ab"):match("()%a"))
show(("balanced (deep (x)) end"):match("%b()"))
show(("front word"):match("%f[%w]%a+"))
show(("one two"):match("(%a+) (%a+)"))
show(("aXa"):gsub("(a)X%1", "Y"))
show(("x=1"):gmatch("%w=%d")())
try(string.match, s, "a%")
try(string.match, s, "%")
try(string.gsub, s, "x%", "y")
try(string.match, s, "[a-")
try(string.match, s, "(")
try(string.match, s, ")")
try(string.gsub, s, "(", "y")
try(string.match, s, "[z-a]")
show(s:match("$"))
show(("abc"):gsub("$", "<"))
show(("abc"):gsub("", "-"))
show(("hello"):match("lo$"))
show(("hello"):find("e", -3))
show(("hello"):find("l", 5))
